void slow_down_wheel(Bike *bike, VerletVector *v, double friction) {
    double f =
        bike->on_ground ? 2.0 : 1.3; // strong rolling friction, tiny air drag
    double damping = exp(-f * BIKE_DT);
    v->prev_x = v->x - (v->x - v->prev_x) * damping;
    v->prev_y = v->y - (v->y - v->prev_y) * damping;
}
void slow_down(Bike *bike) {
    slow_down_wheel(bike, &bike->w1, 1.5);
    slow_down_wheel(bike, &bike->w2, 1.5);
}

void apply_throttle(Bike *bike) {
    int accel = THROTTLE_ACCEL;
    if (!bike->on_ground) {
        accel /= 2.0;
    }
    bike->acc2.x += bike->throttle * accel;
}
void apply_torque(Bike *bike) {
    // bike axis
    double ax = (bike->w2.x - bike->w1.x) / BIKE_LENGTH;
    double ay = (bike->w2.y - bike->w1.y) / BIKE_LENGTH;
    // perpendicular
    double px = -ay, py = ax;

    bike->acc1.x += bike->torque * TORQUE_ACCEL * px;
    bike->acc1.y += bike->torque * TORQUE_ACCEL * py;
    bike->acc2.x -= bike->torque * TORQUE_ACCEL * px;
    bike->acc2.y -= bike->torque * TORQUE_ACCEL * py;
}

void jump(Bike *bike) {
    if (!bike->on_ground)
        return;
    bike->w2.prev_y += JUMP_SPEED * 1.09 * BIKE_DT;
    bike->w1.prev_y += JUMP_SPEED * BIKE_DT;
}

void step(Bike *bike, Platforms p) {
    bike->acc1 = (Vector2){0, GRAVITY};
    bike->acc2 = (Vector2){0, GRAVITY};
    apply_throttle(bike);
    slow_down(bike);
    apply_torque(bike);
    step_verlet(&bike->w1, &bike->acc1, BIKE_DT);
    step_verlet(&bike->w2, &bike->acc2,
                BIKE_DT); // we accelerate via back wheel

    bike->on_ground = 0;
    constraint(bike, p);
}

Bike *create_bike(double x, double y, uint32_t radius) {
    Bike *b = calloc(sizeof(Bike), 1);
    b->radius = radius;
    b->w1.x = x;
    b->w1.y = y;
    b->w1.prev_x = x;
    b->w1.prev_y = y;
    b->w2.x = x + BIKE_LENGTH;
    b->w2.y = y;
    b->w2.prev_x = x + BIKE_LENGTH;
    b->w2.prev_y = y;
    b->on_ground = 0;
    return b;
}
